//! Generates, for the gap telemetry and the coverage table, what the engine
//! itself does with instance members (scanned from src/):
//! - ENGINE_READS: property names it reads (`prop(…, "Name")`,
//!   `f32_prop(…, "Name", …)`, `get(&ustr("Name"))`), so a script writing one
//!   isn't writing into nothing;
//! - ENGINE_FIRES: names the engine mentions as string literals outside the
//!   `event_exists` declaration lists (fire sites often take a name picked
//!   elsewhere), so an event scripts connect to is known to be wired even if
//!   it didn't happen in a run.

use std::collections::BTreeSet;
use std::path::Path;

/// The first capitalised identifier-like string literal in `window`.
fn first_name(window: &str) -> Option<String> {
    let window = &window[..window.find(';').unwrap_or(window.len())];
    let mut rest = window;
    while let Some(q) = rest.find('"') {
        let after = &rest[q + 1..];
        let qe = after.find('"')?;
        let name = &after[..qe];
        if name.chars().next().is_some_and(|c| c.is_ascii_uppercase())
            && name.chars().all(|c| c.is_ascii_alphanumeric())
        {
            return Some(name.to_string());
        }
        rest = &after[qe + 1..];
    }
    None
}

fn collect(text: &str, needle: &str, span: usize, out: &mut BTreeSet<String>) {
    // A needle ending in a quote starts the literal itself: keep the quote.
    let back = usize::from(needle.ends_with('"'));
    let span = if span == 0 { 40 } else { span };
    let mut i = 0;
    while let Some(at) = text[i..].find(needle) {
        let start = i + at + needle.len() - back;
        let mut end = (start + span).min(text.len());
        while !text.is_char_boundary(end) {
            end -= 1;
        }
        if let Some(n) = first_name(&text[start..end]) {
            out.insert(n);
        }
        i = start;
    }
}

/// The text without `fn event_exists … }` bodies.
fn strip_event_lists(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(at) = rest.find("fn event_exists") {
        out.push_str(&rest[..at]);
        let after = &rest[at..];
        match after.find("\n}\n") {
            Some(end) => rest = &after[end + 3..],
            None => return out,
        }
    }
    out.push_str(rest);
    out
}

/// Every capitalised identifier-like string literal.
fn literals(text: &str, out: &mut BTreeSet<String>) {
    for (i, part) in text.split('"').enumerate() {
        if i % 2 == 1
            && part.len() > 2
            && part.chars().next().is_some_and(|c| c.is_ascii_uppercase())
            && part.chars().all(|c| c.is_ascii_alphanumeric())
        {
            out.insert(part.to_string());
        }
    }
}

fn scan(dir: &Path, reads: &mut BTreeSet<String>, fires: &mut BTreeSet<String>) {
    let Ok(rd) = std::fs::read_dir(dir) else { return };
    for e in rd.flatten() {
        let p = e.path();
        if p.is_dir() {
            scan(&p, reads, fires);
            continue;
        }
        let ext = p.extension().and_then(|x| x.to_str()).unwrap_or("");
        if ext != "rs" && ext != "luau" {
            continue;
        }
        // The generated stub table names every member without doing
        // anything with it: it must not count as the engine using them.
        if p.file_name().is_some_and(|n| n == "api_stubs.rs") {
            continue;
        }
        println!("cargo:rerun-if-changed={}", p.display());
        let Ok(text) = std::fs::read_to_string(&p) else { continue };
        if ext == "rs" {
            collect(&text, "prop(", 80, reads);
            // Any property it names for the stored value (reads or writes it:
            // `get(&ustr("X"))`, `insert(ustr("X"), …)`, `mark_prop(r, ustr("X"))`).
            collect(&text, "ustr(", 40, reads);
        }
        // Events: fire sites often take a name picked elsewhere (a match arm,
        // an if, a Luau signal object), so any string literal naming it in the
        // engine counts, outside the `event_exists` declaration lists (which
        // only say an event can be connected).
        literals(&strip_event_lists(&text), fires);
    }
}

fn list(name: &str, doc: &str, set: &BTreeSet<String>) -> String {
    let body: Vec<String> = set.iter().map(|n| format!("    {n:?},")).collect();
    format!("/// {doc} (generated by build.rs).\npub const {name}: &[&str] = &[\n{}\n];\n", body.join("\n"))
}

fn main() {
    let (mut reads, mut fires) = (BTreeSet::new(), BTreeSet::new());
    scan(Path::new("src"), &mut reads, &mut fires);
    let code = list("ENGINE_READS", "Property names the engine reads", &reads)
        + &list("ENGINE_FIRES", "Event names the engine fires", &fires);
    let out = Path::new(&std::env::var("OUT_DIR").unwrap()).join("engine_reads.rs");
    std::fs::write(out, code).unwrap();
    println!("cargo:rerun-if-changed=build.rs");
}
