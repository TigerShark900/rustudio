#!/usr/bin/env python3
"""Generates src/api_stubs.rs from api-dump.json: every member a game script
may reach (Security None; properties by their read security) with a typed
default, so a member rustudio doesn't implement yet still exists — reads give
the default, writes are kept, calls return the typed empty value, events are
connectable signals nothing fires. The runtime only consults this table after
its own lookups fail, so real implementations always win (src/stubs.rs).

Left out: members tagged NotScriptable, and the classes only plugins or
Studio itself reach (names containing Plugin or Studio, and the editor
services below).

    python3 tools/gen_stubs.py            # rewrites src/api_stubs.rs
"""
import json
import os

APP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DUMP = os.path.join(APP, "api-dump.json")
OUT = os.path.join(APP, "src", "api_stubs.rs")

EDITOR_ONLY = {
    "Selection", "ChangeHistoryService", "ScriptEditorService", "DraggerService",
    "ScriptDocument", "ScriptDebugger", "DebuggerManager", "DebuggerBreakpoint",
    "DebuggerWatch", "MultipleDocumentInterfaceInstance", "Toolbar", "DockWidgetPluginGui",
    "QWidgetPluginGui", "ScriptRegistrationService", "PackageUIService", "TestService",
}

# Typed empty values (Luau expressions rustudio's runtime evaluates; "" =
# nothing returned; "@signal" = a connectable signal).
DATATYPE = {
    "Vector3": "Vector3.new()", "Vector2": "Vector2.new()", "CFrame": "CFrame.new()",
    "Color3": "Color3.new()", "UDim": "UDim.new()", "UDim2": "UDim2.new()",
    "BrickColor": 'BrickColor.new("Medium stone grey")', "Rect": "Rect.new()",
    "NumberRange": "NumberRange.new(0)", "NumberSequence": "NumberSequence.new(0)",
    "ColorSequence": "ColorSequence.new(Color3.new())", "Content": '""', "ContentId": '""',
    "Font": 'Font.new("rbxasset://fonts/families/SourceSansPro.json")',
    "Ray": "Ray.new(Vector3.new(), Vector3.new())",
    "Region3": "Region3.new(Vector3.new(), Vector3.new())",
    "PhysicalProperties": "PhysicalProperties.new(Enum.Material.Plastic)",
    "Faces": "Faces.new()", "Axes": "Axes.new()", "Vector3int16": "Vector3int16.new()",
    "Vector2int16": "Vector2int16.new()", "DateTime": "DateTime.now()",
    "RBXScriptSignal": "@signal", "Array": "{}", "Dictionary": "{}", "Map": "{}",
    "Objects": "{}", "Tuple": "", "Variant": "nil", "Function": "nil",
}
PRIMITIVE = {
    "bool": "false", "int": "0", "int64": "0", "float": "0", "double": "0",
    "string": '""', "void": "", "null": "nil",
}


def first_items(dump):
    out = {}
    for e in dump["Enums"]:
        items = e.get("Items") or []
        if not items:
            continue
        zero = next((i for i in items if i.get("Value") == 0), items[0])
        out[e["Name"]] = zero["Name"]
    return out


def default(t, enums):
    if not t:
        return ""
    if isinstance(t, list):  # several return values: the first one's empty value
        return default(t[0], enums) if t else ""
    cat, name = t.get("Category"), t.get("Name")
    if cat == "Primitive":
        return PRIMITIVE.get(name, "nil")
    if cat == "Enum":
        item = enums.get(name)
        return f"Enum.{name}.{item}" if item else "nil"
    if cat == "Class":
        return "nil"
    return DATATYPE.get(name, "nil")


def reachable_class(name):
    return "Plugin" not in name and "Studio" not in name and name not in EDITOR_ONLY


def main():
    dump = json.load(open(DUMP))
    enums = first_items(dump)
    rows = []
    for c in dump["Classes"]:
        if not reachable_class(c["Name"]):
            continue
        for m in c["Members"]:
            tags = [t for t in (m.get("Tags") or []) if isinstance(t, str)]
            if "NotScriptable" in tags:
                continue
            sec = m["Security"]
            kind = m["MemberType"]
            if kind == "Property":
                if sec["Read"] != "None":
                    continue
                read_only = "ReadOnly" in tags or sec["Write"] != "None"
                d = default(m["ValueType"], enums)
            elif kind in ("Function", "Event", "Callback"):
                if sec != "None":
                    continue
                read_only = False
                d = default(m.get("ReturnType"), enums) if kind == "Function" else ""
            else:
                continue
            k = {"Property": "Property", "Function": "Function", "Event": "Event", "Callback": "Callback"}[kind]
            rows.append((c["Name"], m["Name"], k, read_only, d))
    lines = [
        "//! GENERATED by tools/gen_stubs.py from api-dump.json — do not edit by hand.",
        "//! Every member a game script may reach (Security None) with a typed",
        "//! default; consulted by src/stubs.rs only after the runtime's own",
        "//! lookups fail. Each is a stub: it exists, it has no behaviour.",
        "",
        "use crate::api::Kind;",
        "",
        "pub struct Stub {",
        "    pub class: &'static str,",
        "    pub member: &'static str,",
        "    pub kind: Kind,",
        "    pub read_only: bool,",
        "    /// Luau expression of the default / return value (\"\" = none,",
        "    /// \"@signal\" = a connectable signal).",
        "    pub default: &'static str,",
        "}",
        "",
        f"pub static STUBS: [Stub; {len(rows)}] = [",
    ]
    for cls, mem, k, ro, d in rows:
        lines.append(
            f"    Stub {{ class: {json.dumps(cls)}, member: {json.dumps(mem)}, kind: Kind::{k}, "
            f"read_only: {'true' if ro else 'false'}, default: {json.dumps(d)} }},"
        )
    lines.append("];")
    open(OUT, "w").write("\n".join(lines) + "\n")
    counts = {}
    for r in rows:
        counts[r[2]] = counts.get(r[2], 0) + 1
    print(f"wrote {OUT}: {len(rows)} members {counts}")


if __name__ == "__main__":
    main()
