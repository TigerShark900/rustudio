#!/usr/bin/env python3
"""Writes corpus/movement-r15.rbxlx and corpus/movement-r6.rbxlx (round 22's
movement comparison places): movement_course.luau builds the lanes on the
server, movement_probe.luau (StarterPlayerScripts) drives and records the
character. The two differ only in StarterPlayer.GameSettingsAvatar.

Also movement_launch_<game>.luau: for a game's own character, a client
script that puts the probe (with a `local FID_CFG` line in front) in
PlayerScripts as a LocalScript, run by the harness in both engines."""
import os
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
course = escape(open(os.path.join(HERE, "movement_course.luau")).read())
probe = escape(open(os.path.join(HERE, "movement_probe.luau")).read())

# Round 23: the wall-jump lanes alone (a short Studio capture: the full
# course's saved captures stay valid for the other lanes).
WALL = 'local FID_CFG = { segments = { "wall_jump", "wall_jump_diag", "wall_slide", "corner" } }\n'
# The full course leaves them out: it fits its 175 s capture, as recorded.
FULL = 'local FID_CFG = { skip = { "wall_jump", "wall_jump_diag" } }\n'
for rig, avatar, name, pre in (("r15", 1, "movement-r15", FULL), ("r6", 0, "movement-r6", FULL),
                               ("r15", 1, "movement-wall-r15", WALL), ("r6", 0, "movement-wall-r6", WALL)):
    probe_src = escape(pre + open(os.path.join(HERE, "movement_probe.luau")).read())
    xml = f'''<roblox version="4">
<Item class="Workspace" referent="1"><Properties><string name="Name">Workspace</string><float name="Gravity">196.2</float></Properties>
<Item class="Terrain" referent="9"><Properties><string name="Name">Terrain</string></Properties></Item>
<Item class="SpawnLocation" referent="10"><Properties><string name="Name">SpawnLocation</string><bool name="Anchored">true</bool>
<CoordinateFrame name="CFrame"><X>0</X><Y>0.5</Y><Z>30</Z><R00>1</R00><R01>0</R01><R02>0</R02><R10>0</R10><R11>1</R11><R12>0</R12><R20>0</R20><R21>0</R21><R22>1</R22></CoordinateFrame>
<Vector3 name="size"><X>6</X><Y>1</Y><Z>6</Z></Vector3><int name="Duration">0</int></Properties></Item>
</Item>
<Item class="Lighting" referent="2"><Properties><string name="Name">Lighting</string>
<float name="ClockTime">14</float><bool name="GlobalShadows">true</bool><token name="Technology">4</token>
</Properties></Item>
<Item class="ServerScriptService" referent="3"><Properties><string name="Name">ServerScriptService</string></Properties>
<Item class="Script" referent="4"><Properties><string name="Name">BuildCourse</string><ProtectedString name="Source">{course}</ProtectedString></Properties></Item>
</Item>
<Item class="StarterPlayer" referent="5"><Properties><string name="Name">StarterPlayer</string><token name="GameSettingsAvatar">{avatar}</token></Properties>
<Item class="StarterPlayerScripts" referent="6"><Properties><string name="Name">StarterPlayerScripts</string></Properties>
<Item class="LocalScript" referent="7"><Properties><string name="Name">MovementProbe</string><ProtectedString name="Source">{probe_src}</ProtectedString></Properties></Item>
</Item></Item>
<Item class="Players" referent="8"><Properties><string name="Name">Players</string></Properties></Item>
</roblox>
'''
    open(os.path.join(HERE, "corpus", f"{name}.rbxlx"), "w").write(xml)
raw_probe = open(os.path.join(HERE, "movement_probe.luau")).read()
assert "]==]" not in raw_probe
GAMES = {
    # Place B: from a flat spot on its spawn, walking and jumping.
    "place_b": 'local FID_CFG = { origin = Vector3.new(-207.5, -0.37, 119.05), segments = { "walk_stop", "sprint", "turn90", "turn180", "jump_stand", "jump_run", "jump_low", "jump_power" } }',
    # Place C: its ship (PlatformStand + LinearVelocity) where it flies.
    "place_c": 'local FID_CFG = { inplace = true, segments = { "walk_stop", "sprint", "turn90", "turn180" } }',
}
for game, cfg in GAMES.items():
    launch = f"""-- Generated by make_movement_place.py: the movement probe for {game}'s own
-- character, as a LocalScript in PlayerScripts (both engines).
local me = game:GetService("Players").LocalPlayer
local ls = Instance.new("LocalScript")
ls.Name = "MovementProbe"
ls.Source = [==[{cfg}
{raw_probe}]==]
ls.Parent = me:WaitForChild("PlayerScripts")
"""
    open(os.path.join(HERE, f"movement_launch_{game}.luau"), "w").write(launch)
print("ok")
